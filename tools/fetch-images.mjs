// Downloads Philippine mountain photos from Wikimedia Commons, converts them to WebP,
// and writes src/frontend/data/credits.ts with the attribution each license requires.
// Usage: node tools/fetch-images.mjs
import sharp from 'sharp';
import { readFile, writeFile } from 'node:fs/promises';

const UA = { 'User-Agent': 'MMS-Official-Site/1.0 (image build script)' };

// Image list: data/images.json (slug, width, Wikimedia file, place).
const images = JSON.parse(await readFile('data/images.json', 'utf8'));

// Drops HTML tags without a backtracking regex.
const strip = (html = '') =>
  html.split('<').map((part, i) => (i === 0 ? part : part.slice(part.indexOf('>') + 1))).join('').split(/\s+/).filter(Boolean).join(' ');

const api = 'https://commons.wikimedia.org/w/api.php?' + new URLSearchParams({
  action: 'query', format: 'json', titles: images.map((i) => i.file).join('|'),
  prop: 'imageinfo', iiprop: 'url|extmetadata', iiurlwidth: '2400',
});
const data = await (await fetch(api, { headers: UA })).json();
const info = {};
for (const p of Object.values(data.query.pages)) info[p.title] = p.imageinfo[0];
for (const n of data.query.normalized ?? []) info[n.from] = info[n.to];

const credits = [];
for (const img of images) {
  const ii = info[img.file];
  if (!ii) throw new Error(`Not found: ${img.file}`);
  const buf = Buffer.from(await (await fetch(ii.thumburl ?? ii.url, { headers: UA })).arrayBuffer());
  await sharp(buf).rotate().resize({ width: img.width, withoutEnlargement: true }).webp({ quality: 80 }).toFile(`public/images/${img.slug}.webp`);
  const m = ii.extmetadata;
  credits.push({
    src: `/images/${img.slug}.webp`,
    place: img.place,
    title: img.file.replace(/^File:/, '').replace(/\.[a-z]+$/i, ''),
    author: strip(m.Artist?.value) || 'Unknown',
    license: m.LicenseShortName?.value ?? 'See source',
    licenseUrl: m.LicenseUrl?.value ?? '',
    source: ii.descriptionurl,
  });
  console.log(`✓ ${img.slug} — ${credits.at(-1).author} (${credits.at(-1).license})`);
}

await writeFile('src/frontend/data/credits.ts', `// Generated by tools/fetch-images.mjs — do not edit by hand.
export interface PhotoCredit {
  src: string;
  place: string;
  title: string;
  author: string;
  license: string;
  licenseUrl: string;
  source: string;
}

export const photoCredits: PhotoCredit[] = ${JSON.stringify(credits, null, 2)};
`);
